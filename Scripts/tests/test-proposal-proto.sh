# shellcheck shell=bash
# Exercise the real CLI with offline crate archives and immutable-source responses.
# The curl double rejects guessed tags, wrong revisions, and wrong crate paths.
_proposal_proto_fixture() {
    PROPOSAL_TEST_ROOT="$(mktemp -d "$SCRATCH/proposal-proto.XXXXXX")"
    export PROPOSAL_TEST_ROOT
    mkdir -p "$PROPOSAL_TEST_ROOT/bin" "$PROPOSAL_TEST_ROOT/Scripts" \
        "$PROPOSAL_TEST_ROOT/Sources/ZODLSwiftWalletSDK/Modules/Service/GRPC/ProtoBuf/proto"
    cp "$REPO_ROOT/Scripts/update-proposal-proto.sh" "$PROPOSAL_TEST_ROOT/Scripts/"
    git -C "$PROPOSAL_TEST_ROOT" init -q
    python3 - "$PROPOSAL_TEST_ROOT" "${1:-valid}" <<'PY'
import hashlib, io, json, pathlib, sys, tarfile
root, scenario = pathlib.Path(sys.argv[1]), sys.argv[2]
sha = '0123456789abcdef0123456789abcdef01234567'
metadata = {'git': {'sha1': sha}, 'path_in_vcs': 'backend'}
if scenario == 'missing_sha': metadata['git'] = {}
if scenario == 'invalid_sha': metadata['git']['sha1'] = 'main'
if scenario == 'missing_path': del metadata['path_in_vcs']
if scenario == 'invalid_path': metadata['path_in_vcs'] = '../backend'
if scenario == 'absolute_path': metadata['path_in_vcs'] = '/backend'
with tarfile.open(root / 'crate.tar.gz', 'w:gz') as archive:
    if scenario != 'missing_metadata':
        body = b'{' if scenario == 'malformed_metadata' else json.dumps(metadata).encode()
        member = tarfile.TarInfo('zcash_client_backend-0.25.0/.cargo_vcs_info.json')
        member.size = len(body)
        archive.addfile(member, io.BytesIO(body))
checksum = hashlib.sha256((root / 'crate.tar.gz').read_bytes()).hexdigest()
if scenario == 'wrong_checksum': checksum = '0' * 64
if scenario == 'malformed_checksum': checksum = 'oops'
source = 'registry+https://github.com/rust-lang/crates.io-index'
if scenario == 'git': source = 'git+https://github.com/zcash/librustzcash?rev=x#' + sha
lock = f'[[package]]\nname = "zcash_client_backend"\nversion = "0.25.0"\nsource = "{source}"\n'
if scenario != 'missing_checksum': lock += f'checksum = "{checksum}"\n'
(root / 'Cargo.lock').write_text(lock + '\n')
source_path = 'zcash_client_backend' if scenario == 'git' else 'backend'
(root / 'source-url').write_text('https://raw.githubusercontent.com/zcash/librustzcash/' + sha + '/' + source_path + '/proto/proposal.proto')
(root / 'upstream.proto').write_text('syntax = "proto3";\npackage proposal;\nmessage Proposal {}\n')
(root / 'expected.proto').write_text('''// DERIVED FILE -- DO NOT EDIT.
//
// Generated by Scripts/update-proposal-proto.sh from
// zcash/librustzcash/zcash_client_backend/proto/proposal.proto
// at the zcash_client_backend version pinned in Cargo.lock.
//
// The only change from upstream is the added `option swift_prefix` below.
// Bump the dependency and re-run the script rather than editing this file,
// then regenerate proposal.pb.swift.

syntax = "proto3";
package proposal;
option swift_prefix = "Ffi";
message Proposal {}
''')
PY
    cp "$PROPOSAL_TEST_ROOT/expected.proto" "$PROPOSAL_TEST_ROOT/Sources/ZODLSwiftWalletSDK/Modules/Service/GRPC/ProtoBuf/proto/proposal.proto"
    cat > "$PROPOSAL_TEST_ROOT/bin/curl" <<'CURL'
#!/usr/bin/env bash
set -eu
url=''
out=''
while [ "$#" -gt 0 ]; do
    case "$1" in
        -o) out="$2"; shift 2 ;;
        -*) shift ;;
        *) url="$1"; shift ;;
    esac
done
case "$url" in
    https://static.crates.io/crates/zcash_client_backend/zcash_client_backend-0.25.0.crate)
        cp "$PROPOSAL_TEST_ROOT/crate.tar.gz" "$out"
        [ ! -f "$PROPOSAL_TEST_ROOT/fail-archive" ] || exit 22 ;;
    "$(cat "$PROPOSAL_TEST_ROOT/source-url")")
        [ ! -f "$PROPOSAL_TEST_ROOT/fail-source" ] || exit 22
        cp "$PROPOSAL_TEST_ROOT/upstream.proto" "$out" ;;
    *) echo "unexpected URL: $url" >&2; exit 22 ;;
esac
CURL
    chmod +x "$PROPOSAL_TEST_ROOT/bin/curl"
}

_proposal_proto_run() {
    (cd "$PROPOSAL_TEST_ROOT" && PATH="$PROPOSAL_TEST_ROOT/bin:$PATH" bash Scripts/update-proposal-proto.sh "$@")
}

_proposal_proto_unchanged() {
    assert_succeeds "destination remains byte-identical" cmp "$PROPOSAL_TEST_ROOT/expected.proto" \
        "$PROPOSAL_TEST_ROOT/Sources/ZODLSwiftWalletSDK/Modules/Service/GRPC/ProtoBuf/proto/proposal.proto"
}

test_proposal_proto_registry_uses_verified_source_revision() {
    _proposal_proto_fixture
    assert_succeeds "registry provenance resolves immutable source" _proposal_proto_run --check
    _proposal_proto_unchanged
    assert_succeeds "successful update derives expected bytes" _proposal_proto_run
    _proposal_proto_unchanged
}

test_proposal_proto_checksum_mismatch() {
    local scenario
    for scenario in wrong_checksum missing_checksum malformed_checksum; do
        _proposal_proto_fixture "$scenario"
        assert_fails "$scenario rejected" _proposal_proto_run --check
        _proposal_proto_unchanged
        assert_fails "$scenario cannot overwrite destination" _proposal_proto_run
        _proposal_proto_unchanged
    done
}

test_proposal_proto_invalid_provenance() {
    local scenario
    for scenario in missing_metadata malformed_metadata missing_sha invalid_sha missing_path invalid_path absolute_path; do
        _proposal_proto_fixture "$scenario"
        assert_fails "$scenario rejected" _proposal_proto_run --check
        _proposal_proto_unchanged
        assert_fails "$scenario cannot overwrite destination" _proposal_proto_run
        _proposal_proto_unchanged
    done
}

test_proposal_proto_git_revision() {
    _proposal_proto_fixture git
    assert_succeeds "git lock revision remains supported" _proposal_proto_run --check
    _proposal_proto_unchanged
}

test_proposal_proto_schema_drift() {
    _proposal_proto_fixture
    echo 'message NewField {}' >> "$PROPOSAL_TEST_ROOT/upstream.proto"
    assert_fails "schema drift fails check" _proposal_proto_run --check
    _proposal_proto_unchanged
}

test_proposal_proto_failed_update_preserves_destination() {
    _proposal_proto_fixture
    touch "$PROPOSAL_TEST_ROOT/fail-source"
    assert_fails "failed download fails check" _proposal_proto_run --check
    _proposal_proto_unchanged
    assert_fails "failed download fails update" _proposal_proto_run
    _proposal_proto_unchanged
}

test_proposal_proto_failed_archive_download_preserves_destination() {
    _proposal_proto_fixture
    touch "$PROPOSAL_TEST_ROOT/fail-archive"
    assert_fails "failed archive download rejects even complete response bytes" _proposal_proto_run --check
    _proposal_proto_unchanged
    assert_fails "failed archive download cannot update" _proposal_proto_run
    _proposal_proto_unchanged
}
